// Generates the README catalogue, the packs badge and the hero images from
// .claude-plugin/marketplace.json, so the catalogue is the only place to edit.
// Usage: node scripts/build-docs.mjs          write files
//        node scripts/build-docs.mjs --check  exit 1 if any file is out of date (CI)
import { readFileSync, writeFileSync } from 'node:fs'

const GROUPS = ['Foundation', 'Build', 'Decide', 'Ship', 'Upstream']
const market = JSON.parse(readFileSync('.claude-plugin/marketplace.json', 'utf8'))
const packs = market.plugins
const check = process.argv.includes('--check')
const stale = []

const write = (path, text) => {
  let old = ''
  try { old = readFileSync(path, 'utf8') } catch {}
  if (old === text) return
  if (check) stale.push(path)
  else writeFileSync(path, text)
}

// ---------- README catalogue ----------
const repoOf = (p) => p.source?.repo ?? p.source?.url
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|')

function catalogue() {
  const out = []
  for (const group of GROUPS) {
    const rows = packs.filter((p) => (p.metadata?.group ?? 'Upstream') === group)
    if (!rows.length) continue
    out.push(`### ${group}`, '')
    if (group === 'Upstream') {
      out.push('| Pack | Source | What it does |', '|---|---|---|')
      for (const p of rows) out.push(`| \`${p.name}\` | [${repoOf(p)}](https://github.com/${repoOf(p)}) | ${cell(p.description.replace(/^Upstream: /, ''))} |`)
    } else {
      out.push('| Pack | What it does | Try |', '|---|---|---|')
      for (const p of rows) {
        const on = p.defaultEnabled === false ? '' : ' (**on**)'
        out.push(`| \`${p.name}\`${on} | ${cell(p.description)} | ${p.metadata?.try ? '`' + cell(p.metadata.try) + '`' : ''} |`)
      }
    }
    out.push('')
  }
  return out.join('\n')
}

let readme = readFileSync('README.md', 'utf8')
readme = readme.replace(/<!-- catalogue:start -->[\s\S]*<!-- catalogue:end -->/,
  `<!-- catalogue:start -->\n<!-- Generated by scripts/build-docs.mjs from marketplace.json. Do not edit by hand. -->\n\n${catalogue()}<!-- catalogue:end -->`)
readme = readme.replace(/badge\/packs-\d+-/, `badge/packs-${packs.length}-`)
write('README.md', readme)

// ---------- Hero ----------
const THEMES = {
  dark: { bg: '#1F1E1D', panel: '#2A2927', line: '#3D3B38', text: '#F5F4ED', muted: '#A39E93', accent: '#D97757', accentSoft: '#3A2A22', off: '#6B675F' },
  light: { bg: '#FAF9F5', panel: '#F0EEE6', line: '#DDD9CE', text: '#1F1E1D', muted: '#6B675F', accent: '#C15F3C', accentSoft: '#F6E3D9', off: '#B5B0A5' },
}
const HERO = packs.filter((p) => p.metadata?.hero).map((p) => [p.name, p.metadata.hero === 'on'])
const W = 900, H = 420, CX = 450, CY = 205, RX = 330, RY = 135

function hero(t) {
  const nodes = HERO.map(([name, on], i) => {
    const a = -Math.PI / 2 + (i / HERO.length) * 2 * Math.PI
    return { name, on, x: CX + RX * Math.cos(a), y: CY + RY * Math.sin(a), w: name.length * 8.4 + 34 }
  })
  const f = (n) => n.toFixed(1)
  const spokes = nodes.map((n) =>
    `<line x1="${CX}" y1="${CY}" x2="${f(n.x)}" y2="${f(n.y)}" stroke="${n.on ? t.accent : t.line}" stroke-width="${n.on ? 1.6 : 1}"${n.on ? '' : ' stroke-dasharray="3 5"'} opacity="${n.on ? 0.7 : 1}"/>`).join('\n  ')
  const pills = nodes.map((n) => `<g>
    <rect x="${f(n.x - n.w / 2)}" y="${f(n.y - 15)}" width="${f(n.w)}" height="30" rx="15" fill="${n.on ? t.accentSoft : t.panel}" stroke="${n.on ? t.accent : t.line}"/>
    <circle cx="${f(n.x - n.w / 2 + 15)}" cy="${f(n.y)}" r="4" fill="${n.on ? t.accent : 'none'}" stroke="${n.on ? t.accent : t.off}"/>
    <text x="${f(n.x - n.w / 2 + 25)}" y="${f(n.y + 4.5)}" font-size="13" fill="${n.on ? t.text : t.off}">${n.name}</text>
  </g>`).join('\n  ')
  const dots = [0, 1, 2, 3, 4, 5].map((i) => {
    const a = (i / 6) * 2 * Math.PI
    return `<circle cx="${f(CX + 40 * Math.cos(a))}" cy="${f(CY + 40 * Math.sin(a))}" r="4" fill="${t.accent}"/>`
  }).join('')
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" font-family="ui-monospace, SFMono-Regular, Menlo, Consolas, monospace">
  <rect width="${W}" height="${H}" rx="18" fill="${t.bg}"/>
  <ellipse cx="${CX}" cy="${CY}" rx="${RX}" ry="${RY}" fill="none" stroke="${t.line}" stroke-dasharray="2 6"/>
  ${spokes}
  <circle cx="${CX}" cy="${CY}" r="62" fill="${t.panel}" stroke="${t.accent}" stroke-width="2"/>
  <circle cx="${CX}" cy="${CY}" r="40" fill="none" stroke="${t.accent}" stroke-opacity="0.35"/>
  ${dots}
  <circle cx="${CX}" cy="${CY}" r="16" fill="${t.accent}"/>
  ${pills}
  <rect x="${CX - 82}" y="${CY + 74}" width="164" height="24" rx="12" fill="${t.bg}"/>
  <text x="${CX}" y="${CY + 90}" font-size="15" font-weight="700" fill="${t.text}" text-anchor="middle">agentic-harness</text>
  <text x="32" y="${H - 22}" font-size="12" fill="${t.muted}"><tspan fill="${t.accent}">●</tspan> on in this project: ${HERO.filter((p) => p[1]).length}</text>
  <text x="${W - 32}" y="${H - 22}" font-size="12" fill="${t.muted}" text-anchor="end">packs that are off cost <tspan fill="${t.accent}" font-weight="700">0 tokens</tspan></text>
</svg>
`
}
for (const [name, t] of Object.entries(THEMES)) write(`docs/assets/hero-${name}.svg`, hero(t))

if (stale.length) {
  console.error(`✗ out of date: ${stale.join(', ')}. Run: node scripts/build-docs.mjs`)
  process.exit(1)
}
console.log(check ? '✓ docs in sync' : '✓ docs built')
